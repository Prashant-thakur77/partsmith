"""Export the Pydantic contracts to JSON Schema (packages/schemas/json) and TypeScript (apps/web/src/lib/schemas.ts).

Run: `uv run python -m partsmith_schemas.export`. The TypeScript is generated here (no Node dependency) from the JSON Schema
subset Pydantic emits: objects, arrays, tuples, enums/literals, unions, discriminated unions and $refs.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter

from . import commerce, events, measurement, partspec, registry, review, verification
from .events import Event

ROOT = Path(__file__).resolve().parents[3]
JSON_DIR = ROOT / "packages" / "schemas" / "json"
TS_OUT = ROOT / "apps" / "web" / "src" / "lib" / "schemas.ts"

MODULES = [measurement, partspec, verification, events, registry, commerce, review]


def _models() -> dict[str, type[BaseModel]]:
    out: dict[str, type[BaseModel]] = {}
    for mod in MODULES:
        for name in dir(mod):
            obj = getattr(mod, name)
            if (
                isinstance(obj, type)
                and issubclass(obj, BaseModel)
                and obj.__module__ == mod.__name__
                and not name.startswith("_")
            ):
                out[name] = obj
    return out


def _ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return str(s["$ref"]).split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(dict.fromkeys(_ts_type(x) for x in s[key]))
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts_type(x) for x in s["prefixItems"]) + "]"
        return f"Array<{_ts_type(s.get('items', {}))}>"
    if t == "object":
        if "properties" in s:
            return _ts_object(s)
        extra = s.get("additionalProperties")
        return f"Record<string, {_ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(
        str(t), "unknown"
    )


def _ts_object(s: dict[str, Any]) -> str:
    req = set(s.get("required", []))
    lines = [f"  {k}{'' if k in req else '?'}: {_ts_type(v)};" for k, v in s["properties"].items()]
    return "{\n" + "\n".join(lines) + "\n}"


def build() -> tuple[dict[str, Any], str]:
    models = _models()
    defs: dict[str, Any] = {}
    for model in models.values():
        sch = model.model_json_schema(ref_template="#/$defs/{model}", mode="serialization")
        defs.update(sch.pop("$defs", {}))
        defs[model.__name__] = sch
    ev = TypeAdapter(Event).json_schema(ref_template="#/$defs/{model}", mode="serialization")
    defs.update(ev.pop("$defs", {}))
    defs["Event"] = ev
    bundle = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": dict(sorted(defs.items()))}

    out = ["// Generated by `uv run python -m partsmith_schemas.export`. Do not edit by hand.", ""]
    for name, sch in sorted(defs.items()):
        if sch.get("type") == "object" and "properties" in sch:
            out.append(f"export interface {name} {_ts_object(sch)}")
        else:
            out.append(f"export type {name} = {_ts_type(sch)};")
        out.append("")
    return bundle, "\n".join(out)


def main() -> None:
    bundle, ts = build()
    JSON_DIR.mkdir(parents=True, exist_ok=True)
    (JSON_DIR / "partsmith.schema.json").write_text(json.dumps(bundle, indent=2) + "\n")
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(ts)
    print(f"wrote {JSON_DIR / 'partsmith.schema.json'} and {TS_OUT} ({len(bundle['$defs'])} types)")


if __name__ == "__main__":
    main()
