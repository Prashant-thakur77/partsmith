"""Fit-test coupon: a thin plate carrying the part's critical holes / slots / D-bores at three clearances.

Print it in a few minutes, push the real screw / shaft / tab into each column and keep the clearance that fits.
Columns left → right are nominal − step, nominal, nominal + step (default step 0.2 mm). The top-left corner notch
marks the tightest column; 1, 2 and 3 notches on the bottom edge mark the columns.

The result is a normal PartSmith part program (PARAMS + `build(p)` + `result`), so it runs in the sandboxed worker
and every size stays a slider.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Literal

from partsmith_schemas.partspec import BlindHole, DShaftBore, PartSpec, SlotFeature, ThroughHole

CouponKind = Literal["hole", "slot", "d_bore"]


@dataclass(frozen=True)
class CouponFeature:
    id: str
    kind: CouponKind
    diameter_mm: float = 0.0  # hole, d_bore
    length_mm: float = 0.0  # slot (overall, end to end)
    width_mm: float = 0.0  # slot
    flat_depth_mm: float = 0.0  # d_bore: material removed from the circle by the flat


def _ident(raw: str, used: set[str]) -> str:
    name = re.sub(r"[^a-z0-9]+", "_", raw.lower()).strip("_") or "f"
    if name[0].isdigit():
        name = "f_" + name
    base, i = name, 2
    while name in used:
        name, i = f"{base}_{i}", i + 1
    used.add(name)
    return name


def _param(name: str, default: float, lo: float, hi: float, step: float, label: str) -> str:
    return f'    "{name}": ({default:.3f}, {lo:.3f}, {hi:.3f}, {step:g}, "mm", True, "{label}"),'


def coupon_program(
    features: Sequence[CouponFeature],
    *,
    clearance_step_mm: float = 0.2,
    thickness_mm: float = 2.0,
    title: str = "",
) -> str:
    """CadQuery program for a coupon with every feature at −step / 0 / +step clearance."""
    if not features:
        raise ValueError("a coupon needs at least one hole, slot or D-bore")
    used: set[str] = set()
    lines = [
        _param("thickness", thickness_mm, 1.2, 6.0, 0.1, "Coupon thickness"),
        _param("clearance_step", clearance_step_mm, 0.05, 0.5, 0.05, "Clearance step between columns"),
    ]
    rows: list[str] = []
    for f in features:
        fid = _ident(f.id, used)
        if f.kind == "hole":
            if f.diameter_mm <= 0:
                raise ValueError(f"{f.id}: hole diameter must be positive")
            lines.append(_param(f"{fid}_d", f.diameter_mm, 0.5, 60.0, 0.05, f"{fid} nominal diameter"))
            rows.append(f'    ("hole", "{fid}_d", "", ""),')
        elif f.kind == "slot":
            if f.width_mm <= 0 or f.length_mm < f.width_mm:
                raise ValueError(f"{f.id}: slot needs width > 0 and length >= width")
            lines.append(_param(f"{fid}_w", f.width_mm, 0.5, 40.0, 0.05, f"{fid} nominal width"))
            lines.append(_param(f"{fid}_l", f.length_mm, 0.5, 80.0, 0.05, f"{fid} nominal length"))
            rows.append(f'    ("slot", "{fid}_w", "{fid}_l", ""),')
        else:
            if f.diameter_mm <= 0 or not 0 < f.flat_depth_mm < f.diameter_mm / 2:
                raise ValueError(f"{f.id}: D-bore needs diameter > 0 and 0 < flat depth < radius")
            lines.append(_param(f"{fid}_d", f.diameter_mm, 1.0, 40.0, 0.05, f"{fid} nominal diameter"))
            lines.append(_param(f"{fid}_flat", f.flat_depth_mm, 0.1, 10.0, 0.05, f"{fid} flat depth"))
            rows.append(f'    ("d_bore", "{fid}_d", "", "{fid}_flat"),')
    # The title comes from model output: keep it to one line of harmless characters before it enters the program.
    safe_title = re.sub(r"[^A-Za-z0-9 _.,()+-]", "", title)[:80].strip()
    header = f"# Fit-test coupon{': ' + safe_title if safe_title else ''}."
    header += " Columns left to right: nominal - step, nominal, nominal + step."
    return "\n".join(
        [
            header,
            "# Generated by PartSmith. Edit PARAMS only; geometry rebuilds from them. All lengths in mm.",
            "import cadquery as cq",
            "",
            "PARAMS = {  # name: (default, min, max, step, unit, affects_fit, label)",
            *lines,
            "}",
            "",
            "# (kind, size param, length param, flat param) per row",
            "ROWS = [",
            *rows,
            "]",
            "",
            _BUILD,
            "",
            "result = build({k: v[0] for k, v in PARAMS.items()})",
            "",
        ]
    )


_BUILD = '''
def feature_extent(kind, p, a, b, grow):
    """(width, height) of one cut at clearance `grow`."""
    if kind == "slot":
        return p[b] + grow, p[a] + grow
    return p[a] + grow, p[a] + grow


def cutter(kind, p, a, b, flat, grow, x, y, depth):
    base = cq.Workplane("XY").workplane(offset=-0.5).center(x, y)
    if kind == "slot":
        return base.slot2D(p[b] + grow, p[a] + grow, 0).extrude(depth + 1.0)
    d = p[a] + grow
    disc = base.circle(d / 2.0).extrude(depth + 1.0)
    if kind == "d_bore":
        keep = cq.Workplane("XY").workplane(offset=-0.5).center(x, y - p[flat] / 2.0).rect(d, d - p[flat])
        return disc.intersect(keep.extrude(depth + 1.0))
    return disc


def build(p):
    t = p["thickness"]
    step = p["clearance_step"]
    offsets = [-step, 0.0, step]
    gap = 3.0
    cell_w = max(feature_extent(r[0], p, r[1], r[2], step)[0] for r in ROWS) + gap
    heights = [feature_extent(r[0], p, r[1], r[2], step)[1] + gap for r in ROWS]
    width = cell_w * len(offsets) + 2.0 * gap
    height = sum(heights) + 2.0 * gap + 2.0
    plate = cq.Workplane("XY").box(width, height, t, centered=(True, True, False))
    y = height / 2.0 - gap
    for row, row_h in zip(ROWS, heights):
        y = y - row_h / 2.0
        for col, grow in enumerate(offsets):
            x = -width / 2.0 + gap + cell_w * (col + 0.5)
            plate = plate.cut(cutter(row[0], p, row[1], row[2], row[3], grow, x, y, t))
        y = y - row_h / 2.0
    corner = cq.Workplane("XY").workplane(offset=-0.5).center(-width / 2.0, height / 2.0).rect(3.0, 3.0)
    plate = plate.cut(corner.extrude(t + 1.0))
    for col in range(len(offsets)):
        x0 = -width / 2.0 + gap + cell_w * (col + 0.5)
        for k in range(col + 1):
            mark = cq.Workplane("XY").workplane(offset=-0.5).center(x0 + (k - col / 2.0) * 1.6, -height / 2.0)
            plate = plate.cut(mark.rect(0.8, 1.6).extrude(t + 1.0))
    return plate'''.strip("\n")


def features_from_partspec(spec: PartSpec, max_features: int = 4) -> list[CouponFeature]:
    """Critical fit features of a PartSpec: holes (blind holes test as through), slots and D-shaft bores."""
    out: list[CouponFeature] = []
    seen: set[tuple[str, float, float, float]] = set()
    for f in spec.features:
        cf: CouponFeature | None = None
        if isinstance(f, (ThroughHole, BlindHole)):
            cf = CouponFeature(f.id, "hole", diameter_mm=f.diameter.value)
        elif isinstance(f, SlotFeature):
            cf = CouponFeature(f.id, "slot", length_mm=f.length.value, width_mm=f.width.value)
        elif isinstance(f, DShaftBore):
            cf = CouponFeature(f.id, "d_bore", diameter_mm=f.diameter.value, flat_depth_mm=f.flat_depth.value)
        if cf is None:
            continue
        key = (cf.kind, round(cf.diameter_mm, 2), round(cf.width_mm, 2), round(cf.length_mm, 2))
        if key in seen:
            continue  # identical holes only need testing once
        seen.add(key)
        out.append(cf)
        if len(out) >= max_features:
            break
    return out


def coupon_from_partspec(spec: PartSpec, *, max_features: int = 4, clearance_step_mm: float = 0.2) -> str:
    """Coupon program for the part's critical features. Raises ValueError when the part has none."""
    features = features_from_partspec(spec, max_features)
    thickness = min(max(spec.thickness.value, 1.2), 3.0)
    return coupon_program(features, clearance_step_mm=clearance_step_mm, thickness_mm=thickness, title=spec.title)
