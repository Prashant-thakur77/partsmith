/** `/proof`: the evidence as one response, plus the deck's sourced comparison table. Every number comes from a report file. */
import { z } from "zod/mini";

const ProofEntrySchema = z.object({
  id: z.string(),
  title: z.string(),
  headline: z.nullable(z.string()),
  what: z.string(),
  n: z.nullable(z.number()),
  ci: z.nullable(z.string()),
  ci_of: z.nullable(z.string()),
  ground_truth: z.string(),
  label: z.string(),
  detail: z.nullable(z.string()),
  source: z.string(),
  command: z.string(),
});
export type ProofEntry = z.output<typeof ProofEntrySchema>;

const GateSchema = z.object({
  id: z.string(),
  title: z.string(),
  status: z.string(),
  tests: z.nullish(z.number()),
  passed: z.nullish(z.number()),
  failed: z.nullish(z.number()),
  skipped: z.nullish(z.number()),
  command: z.nullish(z.string()),
});

const RateSchema = z.object({ k: z.number(), n: z.number(), rate: z.nullish(z.number()), ci95: z.nullish(z.array(z.number())) });
export type Rate = z.output<typeof RateSchema>;

export const ScaleSchema = z.object({
  generated_at: z.nullish(z.string()),
  label: z.nullish(z.string()),
  runs: z.nullish(z.record(z.string(), z.number())),
  planned: z.nullish(z.record(z.string(), z.number())),
  usd: z.nullish(z.object({ total: z.nullish(z.number()) })),
  paired_b1_vs_ps: z.nullish(
    z.object({ n_pairs: z.number(), metric: z.nullish(z.string()), b1_pass: z.number(), ps_pass: z.number(), p_value: z.nullish(z.number()) }),
  ),
  verified_but_off: z.nullish(
    z.object({
      all_ps: z.nullish(z.object({ k: z.number(), n: z.number(), off_in_height: z.nullish(z.number()), of_runs: z.nullish(z.number()), ci95: z.nullish(z.array(z.number())) })),
      top_only: z.nullish(RateSchema),
      top_and_side: z.nullish(RateSchema),
      helpful_shown: z.nullish(z.boolean()),
    }),
  ),
  stop: z.nullish(z.object({ stop_reason: z.nullish(z.string()), done: z.nullish(z.number()), not_started: z.nullish(z.number()) })),
  understanding: z.nullish(
    z.object({
      family_correct: z.nullish(RateSchema),
      template_chosen_correct: z.nullish(RateSchema),
      broken_region_kept_on_broken: z.nullish(RateSchema),
      broken_region_kept_on_intact: z.nullish(RateSchema),
    }),
  ),
  /** Per suite, how many full-loop runs measured from each outline source ("threshold", "sam-3.1", "no measure line"). */
  mask_sources: z.nullish(z.record(z.string(), z.record(z.string(), z.number()))),
  sam: z.nullish(
    z.object({
      ran: z.nullish(z.number()),
      planned: z.nullish(z.number()),
      errors: z.nullish(z.number()),
      mask_returned: z.nullish(RateSchema),
      when_returned: z.nullish(z.object({ n: z.nullish(z.number()), iou_median: z.nullish(z.number()), boundary_mean_mm_median: z.nullish(z.number()) })),
    }),
  ),
  wonder: z.nullish(z.object({ accepted_with_citation: z.nullish(RateSchema) })),
  voice: z.nullish(z.object({ speech: z.nullish(z.string()), spoken: z.nullish(RateSchema), typed: z.nullish(RateSchema) })),
  source: z.string(),
  command: z.string(),
});
export type ScaleReport = z.output<typeof ScaleSchema>;

export const ProofSchema = z.object({
  report_date: z.nullable(z.string()),
  report_mode: z.nullish(z.string()),
  errors: z.array(ProofEntrySchema),
  outcomes: z.array(ProofEntrySchema),
  instruments: z.array(ProofEntrySchema),
  tests: z.object({ generated_at: z.nullish(z.string()), git: z.nullish(z.string()), gates: z.array(GateSchema), source: z.string() }),
  audit: z.array(z.object({ suite: z.string(), runs: z.number(), verified: z.number(), within: z.number(), off: z.number() })),
  scale: z.nullable(ScaleSchema),
  not_tested: z.object({
    real_phone_photos_measured: z.number(),
    real_parts_with_ruler_ground_truth: z.number(),
    real_prints_or_repairs_logged: z.number(),
    person_reviewed_rounds: z.number(),
    scripted_review_decisions: z.number(),
  }),
});
export type Proof = z.output<typeof ProofSchema>;

/** A rate as "k of n", with its interval when the report has one. */
/** Across every suite: runs measured from a SAM 3.1 mask, and runs that reached measuring at all. Null when the report has none. */
export function maskSourceTotals(sources: Record<string, Record<string, number>> | null | undefined): { sam: number; measured: number } | null {
  let sam = 0;
  let measured = 0;
  for (const suite of Object.values(sources ?? {})) {
    for (const [source, count] of Object.entries(suite)) {
      if (source === "no measure line") continue;
      measured += count;
      if (source.startsWith("sam")) sam += count;
    }
  }
  return measured ? { sam, measured } : null;
}

export function rateText(r: Rate | null | undefined): { headline: string; ci: string | null } | null {
  if (!r) return null;
  const ci = r.ci95 && r.ci95.length === 2 ? `[${r.ci95[0]}, ${r.ci95[1]}]` : null;
  return { headline: `${r.k} of ${r.n}`, ci };
}

/** The comparison table the deck also shows: `/deck/data.json`, generated by tools/deck_data.py. */
const DeckSchema = z.object({
  landscape: z.object({
    columns: z.array(z.string()),
    rows: z.array(z.object({ name: z.string(), cells: z.array(z.string()), why: z.string(), ours: z.optional(z.boolean()) })),
    finding: z.string(),
    source: z.string(),
    source_url: z.string(),
  }),
});
export type Landscape = z.output<typeof DeckSchema>["landscape"];

export async function fetchLandscape(signal?: AbortSignal): Promise<Landscape> {
  const r = await fetch("/deck/data.json", { signal });
  if (!r.ok) throw new Error(`deck data: ${r.status}`);
  return DeckSchema.parse(await r.json()).landscape;
}
