// Unit tests for the fail → fix history reducer (node --test; no browser, no network). Reads committed replays.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { EventSchema } from "../src/lib/api-types.ts";
import { editsText, headline, keepReason, keptRound, parseViews, roundsFromEvents, sizeSetsMaxError, verdictFromLabel } from "../src/lib/fix-rounds.ts";

const REPLAYS = new URL("../../../data/replays/", import.meta.url);
// replays are found by their demo sample (data/replays/seed_index.json), so a re-seed with new job ids keeps working
const SEED_INDEX = JSON.parse(readFileSync(new URL("seed_index.json", REPLAYS), "utf8"));
const replayOf = (sample) => SEED_INDEX[sample];
// the multi-round L-bracket run is pinned as a fixture (a mock-provider replay, 2026-10-28): the committed replays are
// regenerated by every seed (now on live models), so a test that needs a known 5-round story must not read them
const PINNED_L_BRACKET = "../../apps/web/test/fixtures/l-bracket-mock"; // relative to data/replays/
// a live spacer run that verified on its first build (2026-10-29, first live seed); later seeds may need a fix round
const PINNED_SPACER = "../../apps/web/test/fixtures/spacer-first-build";

function replayEvents(id) {
  return readFileSync(new URL(`${id}/run.jsonl`, REPLAYS), "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => EventSchema.parse(JSON.parse(l)));
}

const ev = (t, seq, extra) => EventSchema.parse({ job: "j", seq, ts: seq, t, ...extra });

test("the L-bracket replay shows four failing rounds and a verified fifth, all from its own events", () => {
  const s = roundsFromEvents(replayEvents(PINNED_L_BRACKET));
  assert.equal(s.rounds.length, 5);
  assert.deepEqual(
    s.rounds.map((r) => r.verdict),
    ["best_effort", "best_effort", "best_effort", "best_effort", "verified"],
  );
  assert.equal(s.final?.verified, true);
  assert.equal(s.limitMm, 0.5);
  assert.equal(s.headline, "Verified after 5 rounds (4 fixes)");
  assert.equal(s.keptIter, 5);
  const [r1, r2, , , r5] = s.rounds;
  assert.equal(r1.firstBuild, true);
  assert.equal(editsText(r1), "first build");
  assert.deepEqual(r2.edits, [{ param: "corner_radius", from: 2, to: 1.5 }]);
  assert.equal(editsText(r2), "corner_radius 2.00→1.50 mm");
  // the round's error is the verifier's max_error_mm metric, not a number made here
  assert.ok(Math.abs(r2.maxErrorMm - 7.135) < 1e-9);
  assert.ok(Math.abs(r5.maxErrorMm - 0.163) < 1e-9);
  // per-view numbers come from the server's own text: both views once the agent inspected them
  assert.deepEqual(r1.views.map((v) => v.view), ["top", "side"]);
  assert.equal(r1.views[0].withinLimit, false);
  assert.equal(r5.views.every((v) => v.withinLimit === true), true);
  // each round links its residual overlays (top + side)
  assert.deepEqual(r1.overlays.map((o) => o.view), ["top", "side"]);
  assert.match(r5.overlays[0].url, /^\/api\/v1\/blobs\//);
});

test("a job verified on its first build says so and runs no agent", () => {
  const s = roundsFromEvents(replayEvents(PINNED_SPACER));
  assert.equal(s.rounds.length, 1);
  assert.equal(s.rounds[0].verdict, "verified");
  assert.equal(s.headline, "Passed on the first build");
  assert.equal(s.rounds[0].views.length, 1);
});

test("a best-effort job keeps its final status honest", () => {
  const s = roundsFromEvents(replayEvents(replayOf("demo-hook")));
  assert.equal(s.rounds.length, 6);
  assert.equal(s.final?.status, "best_effort");
  // the shipped round is the one the done event names; later attempts are called discarded, never "final"
  assert.ok(s.rounds.some((r) => r.iter === s.keptIter));
  const later = s.rounds.filter((r) => r.iter > s.keptIter).length;
  assert.equal(s.headline, later ? `Best effort: kept round ${s.keptIter} of 6; ${later} later ${later === 1 ? "try" : "tries"} discarded` : "Best effort after 6 rounds");
  assert.ok(s.rounds.every((r) => r.verdict !== "verified"));
});

test("a verified round followed by a worse try: the verified round is kept, the later one is discarded", () => {
  const events = [
    ev("stage", 1, { ctx: "a", stage: "verify", status: "ok", label: "Verified: top: IoU 0.988, Hausdorff 0.38 mm", iter: 1 }),
    ev("iteration", 2, { ctx: "a", iter: 1, strategy: "template", edits: [], hausdorff_mm: 0.38, iou: 0.97, passed_tests: 24, total_tests: 24 }),
    ev("metric", 3, { ctx: "a", iter: 1, name: "max_error_mm", value: 0.38, unit: "mm" }),
    ev("stage", 4, { ctx: "b", stage: "verify", status: "ok", label: "best effort: top: IoU 0.930, Hausdorff 3.02 mm", iter: 2 }),
    ev("iteration", 5, { ctx: "b", iter: 2, strategy: "template", edits: [{ param: "knuckle_count", from: 2, to: 3 }], hausdorff_mm: 3.71 }),
    ev("metric", 6, { ctx: "b", iter: 2, name: "max_error_mm", value: 3.71, unit: "mm" }),
    ev("done", 7, { ctx: "a", verified: true, status: "verified", summary: { max_error_mm: 0.38 } }),
  ];
  const s = roundsFromEvents(events);
  assert.equal(s.keptIter, 1);
  assert.equal(s.headline, "Verified on the first build; 1 later try discarded");
  // without trace contexts the done summary's max error still finds it
  const noCtx = roundsFromEvents(events.map((e) => ({ ...e, ctx: "" })));
  assert.equal(noCtx.keptIter, 1);
  // and with neither, the last round is assumed (the old behaviour)
  assert.equal(keptRound(s.rounds, "", null), 2);
});

test("verdicts come only from the verify stage label prefix; anything else is unknown", () => {
  assert.equal(verdictFromLabel("Verified: top: IoU 0.99", "ok"), "verified");
  assert.equal(verdictFromLabel("best effort: top: IoU 0.6", "ok"), "best_effort");
  assert.equal(verdictFromLabel("failed: no solid", "ok"), "failed");
  assert.equal(verdictFromLabel("Verified", "fail"), "failed");
  assert.equal(verdictFromLabel("looks great", "ok"), "unknown");
});

test("per-view parsing reads the server's format and ignores junk", () => {
  assert.deepEqual(parseViews("top: IoU 0.640, Hausdorff 10.57 mm at (1, 2); side: IoU 0.917, Hausdorff 1.34 mm"), [
    { view: "top", iou: 0.64, hausdorffMm: 10.57 },
    { view: "side", iou: 0.917, hausdorffMm: 1.34 },
  ]);
  assert.deepEqual(parseViews("nothing here"), []);
});

test("a running job reports rounds so far; a round without a verify label stays unknown", () => {
  const events = [
    ev("artifact", 1, { kind: "residual_heatmap", sha: "a", url: "/x.png", iter: 1, label: "round 1: residual_top" }),
    ev("iteration", 2, { iter: 1, strategy: "template", edits: [], analysis: "first build", hausdorff_mm: 2.5, iou: 0.9, passed_tests: 3, total_tests: 5 }),
  ];
  const s = roundsFromEvents(events);
  assert.equal(s.headline, "1 round so far");
  assert.equal(s.rounds[0].verdict, "unknown");
  assert.equal(s.rounds[0].maxErrorMm, 2.5);
  assert.equal(s.rounds[0].overlays.length, 1);
  assert.equal(s.limitMm, null);
  assert.equal(headline([], null), "No build yet.");
});

test("free-code rounds that rewrite the program are named, and set_params fills missing edits", () => {
  const events = [
    ev("iteration", 1, { iter: 2, strategy: "free_code", edits: [], diff: "--- a\n+++ b\n" }),
    ev("iteration", 2, { iter: 3, strategy: "template", edits: [] }),
    ev("tool_call", 3, { stage: "fix", name: "set_params", args: { edits: [{ param: "width", from: 30, to: 24.6 }] }, result: "committed round 3: width", ok: true }),
  ];
  const s = roundsFromEvents(events);
  assert.equal(editsText(s.rounds[0]), "program rewritten (free code)");
  assert.equal(editsText(s.rounds[1]), "width 30.00→24.60 mm");
});

test("a round's max error can come from a measured size, larger than every outline gap", () => {
  const views = [{ view: "top", hausdorffMm: 0.17, withinLimit: true }, { view: "side", hausdorffMm: 0.08, withinLimit: true }];
  assert.equal(sizeSetsMaxError({ maxErrorMm: 0.252, hausdorffMm: 0.168, views }), true);
  assert.equal(sizeSetsMaxError({ maxErrorMm: 0.17, hausdorffMm: 0.168, views }), false);
  assert.equal(sizeSetsMaxError({ maxErrorMm: null, hausdorffMm: 0.168, views }), false);
  assert.equal(sizeSetsMaxError({ maxErrorMm: 0.3, hausdorffMm: null, views: [] }), false);
});

// Wall-hook shape (numbers from the recorded run j_261029_5e9d54d1): round 5 kept at 4.70 mm over round 2 at 3.22 mm.
function hookEvents(shortfall) {
  const rows = [
    [1, 5.016, 12],
    [2, 3.224, 14],
    [3, 3.714, 14],
    [4, 4.428, 15],
    [5, 4.696, 16],
    [6, 4.622, 16],
  ];
  const out = [];
  let seq = 0;
  for (const [iter, err, passed] of rows) {
    out.push(ev("stage", seq++, { stage: "verify", status: "ok", iter, label: "best effort: top: IoU 0.9, Hausdorff 1.0 mm" }));
    out.push(ev("iteration", seq++, { iter, strategy: "template", edits: [], ctx: `c${iter}`, hausdorff_mm: err, passed_tests: passed, total_tests: 17, ...(shortfall ? { pass_shortfall: shortfall[iter - 1] } : {}) }));
    out.push(ev("metric", seq++, { iter, name: "max_error_mm", value: err }));
  }
  out.push(ev("done", seq++, { verified: false, status: "best_effort", summary: { max_error_mm: 4.696 }, ctx: "c5" }));
  return out;
}

test("the kept round says why it beat rounds with a lower max error (older run: rule + test counts as context)", () => {
  const s = roundsFromEvents(hookEvents(null));
  assert.equal(s.keptIter, 5);
  const why = keepReason(s.rounds, s.keptIter);
  assert.match(why, /^Kept round 5 \(4\.70 mm\) although rounds 2, 3, 4 and 6 had a lower max error \(lowest: round 2, 3\.22 mm\)\./);
  assert.match(why, /closest to passing overall/);
  assert.match(why, /Tests passed: 16\/17 for round 5, 14\/17 for round 2 \(this run did not record the shortfall itself\)\./);
});

test("new runs quote the keep rule's own number for the kept round and the lowest-error rival", () => {
  const s = roundsFromEvents(hookEvents([30.1, 21.4, 19.9, 17.2, 12.35, 12.6]));
  assert.equal(s.rounds[4].passShortfall, 12.35);
  assert.match(keepReason(s.rounds, s.keptIter), /Shortfall 12\.35 for round 5 vs 21\.40 for round 2\.$/);
  // nothing to explain when the kept round also has the lowest max error
  assert.equal(keepReason(s.rounds, 2), null);
});
